// Generates native/.../LibraryData.kt from src/data.js so the native app and the web source share one library.
// The starter plans in data.js are only for the old web version: the app starts empty.
import { LIBRARY, STANDARDS } from '../src/data.js';
import { writeFileSync } from 'node:fs';

const d = (x) => (Number.isInteger(x) ? x + ".0" : String(x));
const q = (s) => JSON.stringify(s).replace(/\$/g, '\$');
const list = (a) => `listOf(${a.map(q).join(', ')})`;
const lines = LIBRARY.map((e) =>
  `    Exercise(${q(e.id)}, ${q(e.name)}, ${q(e.cat)}, ${list(e.primary)}, ${list(e.secondary)}, ${d(e.std)}, ${d(e.bw)}, ${e.pair}, stdF = ${d(e.stdF)}${e.noScore ? ', noScore = true' : ''})`);
const S = STANDARDS;
const nums = (o) => `mapOf(${Object.entries(o).map(([k, v]) => `${q(k)} to ${d(v)}`).join(', ')})`;
const sex = (x) => `SexStandard(${d(x.refKg)}, ${d(x.exponent)}, ${nums(x.levels)})`;
const standards = `val STANDARDS = Standards(
    male = ${sex(S.male)},
    female = ${sex(S.female)},
    age = listOf(${S.age.map(([a, f]) => `${d(a)} to ${d(f)}`).join(', ')}),
    percentiles = ${nums(S.percentiles)},
    femaleRatio = ${nums(S.femaleRatio)},
    femaleRatioDefault = ${d(S.femaleRatioDefault)},
    bodyweightFloor = ${d(S.bodyweightFloor)},
    nutrition = Nutrition(${['waterMlPerKg', 'waterMinMl', 'waterMaxMl', 'proteinGPerKg', 'proteinStepG'].map((k) => `${k} = ${d(S.nutrition[k])}`).join(', ')}),
)`;
writeFileSync('native/app/src/main/java/com/wilfrombdn/heavynt/LibraryData.kt',
`// GENERATED by scripts/gen-kotlin-data.mjs from src/data.js. Do not edit by hand.
package com.wilfrombdn.heavynt

val LIBRARY: List<Exercise> = listOf(
${lines.join(',\n')}
)

${standards}
`);
console.log(LIBRARY.length, 'exercises');
